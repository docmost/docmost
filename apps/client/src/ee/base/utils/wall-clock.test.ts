import { describe, expect, it } from "vitest";
import { fromWallString, toWallString } from "./wall-clock";

const NY = "America/New_York";
const BERLIN = "Europe/Berlin";

describe("toWallString", () => {
  it.each([
    ["2026-11-12T15:00:00.000Z", NY, "2026-11-12 10:00:00"],
    ["2026-11-12T15:00:00.000Z", BERLIN, "2026-11-12 16:00:00"],
    ["2026-11-12T15:00:00.000Z", "Pacific/Kiritimati", "2026-11-13 05:00:00"],
    ["2026-11-12T15:00:00.000Z", "+05:30", "2026-11-12 20:30:00"],
    ["2026-11-12T10:15:30.123Z", NY, "2026-11-12 05:15:30"],
    ["2026-03-08T06:30:00.000Z", NY, "2026-03-08 01:30:00"],
    ["2026-03-08T07:30:00.000Z", NY, "2026-03-08 03:30:00"],
    ["2026-11-01T05:50:00.000Z", NY, "2026-11-01 01:50:00"],
    ["2026-11-01T06:10:00.000Z", NY, "2026-11-01 01:10:00"],
    ["2026-10-25T00:50:00.000Z", BERLIN, "2026-10-25 02:50:00"],
    ["2026-10-25T01:10:00.000Z", BERLIN, "2026-10-25 02:10:00"],
  ])("reads %s in %s as %s", (instant, timeZone, wall) => {
    expect(toWallString(instant, timeZone)).toBe(wall);
  });
});

describe("fromWallString", () => {
  it.each([
    ["2026-11-12 10:00:00", NY, "2026-11-12T15:00:00.000Z"],
    ["2026-11-12 10:00", NY, "2026-11-12T15:00:00.000Z"],
    ["2026-11-12 10:00:00", BERLIN, "2026-11-12T09:00:00.000Z"],
    ["2026-11-12 10:00:00", "+05:30", "2026-11-12T04:30:00.000Z"],
    ["2026-11-12 23:59:59", NY, "2026-11-13T04:59:59.000Z"],
    ["2026-03-08 02:30:00", NY, "2026-03-08T07:30:00.000Z"],
    ["2026-03-29 02:30:00", BERLIN, "2026-03-29T01:30:00.000Z"],
    ["2026-11-01 01:30:00", NY, "2026-11-01T05:30:00.000Z"],
    ["2026-10-25 02:30:00", BERLIN, "2026-10-25T00:30:00.000Z"],
  ])("reads %s in %s as %s", (wall, timeZone, instant) => {
    expect(fromWallString(wall, timeZone)).toBe(instant);
  });

  it.each(["", "2026-11-12", "2026-11-12T10:00:00", "2026-13-01 10:00:00", "2026-11-12 24:00:00", "9999-12-31 23:00:00"])(
    "throws a RangeError for %p",
    (value) => {
      expect(() => fromWallString(value, NY)).toThrow(RangeError);
    },
  );
});
